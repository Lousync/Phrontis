/**
 * AI 教学 · 讲课口径注入串拼装 —— **零依赖纯函数**（专为契约脚本直接 import）。
 *
 * 为什么单独拆出来：
 * - 基础人设里的「简洁直接」会把讲课压成总结；而 2026-11-04 版的 teachStyleHint 又要求
 *   一条回答写完整篇小讲义（定义 → 推导 → 例题 → 总结），模型只能一次倒完。两种极端都不是教书。
 * - 2026-11-10 用户拍板：默认「小步引导」——一条回答只推进一个台阶，讲完给一个具体检查
 *   问题并停下等学生回答；想恢复旧行为可在 设置 → AI → 教学 切「整段精讲」。
 * - 文案单独放这里后，契约脚本 `verify-teach-style.mjs` 可以 strip 类型直接跑真实实现，
 *   改坏提示词不会静默通过（旧版只做 agentService 字符串存在性检查）。
 *
 * 不变量：
 *   · 只对 `source === 'aiTeaching'` 注入（agentService 侧门控，不在本文件判断）；
 *   · 缺省 / 脏值一律回落 `stepwise`，不能因设置损坏退回旧的大段输出；
 *   · 两种模式都以 `\n\n` 开头，与 agentService 其它 hint 的拼接口径一致。
 */

export type TeachStyleMode = 'stepwise' | 'expanded'

/** 默认模式：小步引导（一条回答一个台阶 + 一个检查问题并停下） */
export const DEFAULT_TEACH_STYLE_MODE: TeachStyleMode = 'stepwise'

/** 非法 / 缺省值一律回落到默认小步（设置被手改成脏值时不能让讲课退回旧行为） */
export function normalizeTeachStyleMode(value: unknown): TeachStyleMode {
  return value === 'expanded' ? 'expanded' : 'stepwise'
}

/**
 * 旧口径：保留给「整段精讲」设置。
 * 文案与 2026-11-04 版逐字一致，避免老用户切回时行为漂移。
 */
const EXPANDED_HINT = '\n\n【讲课口径（AI教学·整段精讲）】基础规则里的「简洁直接」只适用于事务性回答，不适用于讲课 / 教材。讲知识点必须展开：问题/场景 → 前置桥接 → 定义 → 直觉 → 推导（每步为什么）→ 例题 → 反例/易错 → 检查 → 最后才总结；禁止用要点列表代替推导，禁止把素材的总结句改写一遍就交差。素材只有标题/摘要时明确说“素材不足”，用通用知识补讲要标“AI 补充”。'

/**
 * 默认口径：小步引导。
 *
 * 关键约束（契约脚本逐条锁）：
 *   · 一条回答只推进一个台阶（一个概念 / 一步推导 / 一个例子，正文约 300–500 字）；
 *   · 讲完立刻停，用正文一句话问检查问题并等待学生回答，禁止自问自答；
 *   · 答对推进下一台阶，答错只纠正当前这一步；
 *   · 禁止一条回答同时给「定义 + 推导 + 例题 + 总结」；
 *   · 检查问题不用 ask 卡，quiz 快检只在讲完一个完整知识点后出；
 *   · 用户明确要求一次讲完 / 完整讲义 / 整段精讲 / 快速过完整节时才展开；
 *   · 教材 / 讲义仍可一次性落盘，但对话里不贴全文。
 */
const STEPWISE_HINT = '\n\n【讲课口径（AI教学·小步引导）】'
  + '这条只约束讲课、答疑和教材中的知识点讲解；查资料、改文件、日程等事务性回答仍按基础规则简洁直接。'
  + '把讲课当成师生对话，不是写教材。一条回答只推进一个台阶：一个概念、一步推导或一个例子（正文约 300–500 字，公式/代码不计）。'
  + '讲完立刻停下，用正文里的一句话问一个具体、可回答的检查问题，然后等待学生回答；不要自问自答，不要在同一条回答里继续下一台阶，也不要用“接下来我们看…”把下一台阶带出来。'
  + '学生回答后先判断：答对→再推进下一台阶；答错或卡住→只纠正当前这一步，换更小的例子或类比，不要重讲整节，也不要重复原文。'
  + '禁止在一条回答里同时给出“定义 + 推导 + 例题 + 总结”，禁止用要点列表代替推导，禁止把整节内容一次倒完。'
  + '检查问题用正文一句话；`ask` 只用于需要学生做选择/确认的场合，不要每个台阶都弹选择卡。`quiz` 快检只在讲完一个完整知识点后出，一条回答最多一道；单个台阶的检查不要用 quiz 围栏。'
  + '例外：学生明确说“一次讲完 / 给我完整讲义 / 整段精讲 / 快速过完整节 / 直接说不用互动”时才展开；展开前先用一句话说明“这会比较长”。'
  + '教材/讲义类产物仍可一次性落盘成文档（不拆成多轮写文件），但对话里只回一句“教材已生成，先读第 X 节，读完把卡点告诉我”，不要把全文贴进对话。'
  + '课程里的旧版讲课手册若与本条冲突，以本条为准；手册里的教材结构、素材纪律、出题边界仍然有效。'
  + '素材只有标题/摘要时明确说“素材不足”；用通用知识补讲标“AI 补充”。'

export function buildTeachStyleHint(mode: TeachStyleMode = DEFAULT_TEACH_STYLE_MODE): string {
  return mode === 'expanded' ? EXPANDED_HINT : STEPWISE_HINT
}
